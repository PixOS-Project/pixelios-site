#!/usr/bin/env python3
"""Render the generated progress tables of the site from data/progress.json.

  python3 tools/render_progress.py            rewrite the blocks between <!-- progress:NAME:begin --> and <!-- progress:NAME:end -->
  python3 tools/render_progress.py --check    exit 1 and name each file whose block differs from what the data renders (no write)

data/progress.json is written by the maintainers' export (rung, state, number, date, run label, evidence tag; nothing private). Prose
around the blocks is hand-written; the numbers inside a block are owned by this generator, so a hand edit there is reported by --check.
Blocks: `status` (docs/STATUS.md, newest measurements), `features` (docs/STATUS.md, the feature list and known issues) and
`ladder` (docs/MILESTONES.md, every rung).
"""
import json, os, re, sys

SITE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STATE = {
    "done": "**done**",
    "done-one-run": "**done** (one run)",
    "met-one-run": "target met, one run",
    "met-with-stopgap": "target met with a stopgap",
    "partial": "partial",
    "open": "open",
    "superseded": "replaced",
}
STREAM_TITLE = {"GPU": "GPU", "Wi-Fi": "Wi-Fi", "Bluetooth": "Bluetooth", "Tooling": "Tooling"}


def esc(s):
    return s.replace("|", "\\|")


def evidence(r):
    if not r["date"]:
        return "not started"
    runs = ", ".join("`%s`" % x.strip() for x in r["run"].split(";") if x.strip())
    return "%s, %s, run%s %s" % (r["tag"], r["date"], "s" if ";" in r["run"] else "", runs)


def table(data, with_metric):
    out = []
    head = "| Rung | State | Result | Evidence |" if not with_metric else "| Rung | What is measured | State | Result | Evidence | Note |"
    out += [head, "|" + "---|" * (head.count("|") - 1)]
    last = None
    for r in data["rows"]:
        if r["stream"] != last:
            last = r["stream"]
            out.append("| **%s** |%s" % (STREAM_TITLE.get(last, last), " |" * (head.count("|") - 2)))
        state = STATE.get(r["state"], r["state"])
        if with_metric:
            out.append("| %s | %s | %s | %s | %s | %s |" % tuple(esc(x) for x in (r["id"], r["rung"], state, r["headline"], evidence(r), r["note"] or "")))
        else:
            out.append("| %s | %s | %s | %s |" % tuple(esc(x) for x in (r["id"], state, r["headline"], evidence(r))))
    return "\n".join(out)


def features(data):
    out = ["Feature list as of **%s**. Every row was observed on hardware in the runs named; the list leaves out anything not yet seen on the phone." % data.get("features_as_of", ""), "",
           "| Feature | What the run showed | Runs | Date |", "|---|---|---|---|"]
    for f in data.get("features", []):
        out.append("| %s | %s | %s | %s |" % tuple(esc(x) for x in (f["feature"], f["shows"], f["run"], f["date"])))
    if data.get("known_issues"):
        out += ["", "**Known issues** (observed):", ""] + ["- " + i for i in data["known_issues"]]
    return "\n".join(out)


def render_block(name, data):
    hdr = "<!-- progress:%s:begin (generated by tools/render_progress.py from data/progress.json; do not edit) -->" % name
    ftr = "<!-- progress:%s:end -->" % name
    if name == "features":
        return "\n".join([hdr, features(data), ftr])
    intro = "Numbers as of **%s**, from the project's milestone ladder. \"One run\" means a single hardware run that has not been repeated." % data["as_of"]
    body = table(data, name == "ladder")
    return "\n".join([hdr, intro, "", body, ftr])


def apply(text, name, data):
    rx = re.compile(r"<!-- progress:%s:begin.*?-->.*?<!-- progress:%s:end -->" % (name, name), re.S)
    if not rx.search(text):
        return None
    return rx.sub(lambda m: render_block(name, data), text)


TARGETS = (("docs/STATUS.md", "features"), ("docs/STATUS.md", "status"), ("docs/MILESTONES.md", "ladder"))


def run(site=SITE, check=False):
    data = json.load(open(os.path.join(site, "data", "progress.json"), encoding="utf-8"))
    bad = []
    for rel, name in TARGETS:
        path = os.path.join(site, rel)
        text = open(path, encoding="utf-8").read()
        new = apply(text, name, data)
        if new is None:
            bad.append("%s has no progress:%s block" % (rel, name))
        elif new != text:
            bad.append("%s progress:%s block differs from data/progress.json" % (rel, name))
            if not check:
                open(path, "w", encoding="utf-8").write(new)
    return bad


if __name__ == "__main__":
    chk = "--check" in sys.argv[1:]
    bad = run(check=chk)
    for b in bad:
        print(("DRIFT " if chk else "rendered/") + b)
    print("RESULT: %s render-progress%s" % ("FAIL" if (bad and chk) or any("no progress" in b for b in bad) else "PASS", " drift=%d" % len(bad) if chk else ""))
    sys.exit(1 if (bad and chk) or any("no progress" in b for b in bad) else 0)
